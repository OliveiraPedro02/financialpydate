"""
Regenerate ``financialpydate/calendars`` from QuantLib.

Run from the repository root with ``uv run python -m financialpydate.update_files.get_holidays``.

Writes:

- ``calendars/holidays.npz``: for every calendar, its numpy weekmask and its holidays as int32 day numbers (days since
  1970-01-01), compressed. `financialpydate.calendar_store` reads it lazily, one calendar at a time.
- ``calendars/__init__.py``: ``all_calendars`` plus one lazy attribute per calendar, so
  ``from financialpydate.calendars import Brazil, all_calendars`` builds nothing at import time. It replaces the
  ``calendars/<name>.py`` and ``calendars/all_calendar.py`` modules of earlier versions, which are deleted.

Each calendar is stored as a numpy weekmask plus the holidays that fall on its working weekdays. Listing every
weekend as a holiday (with ``weekmask='1111111'``) gives the same business days but makes ``np.busday_offset`` about 3x
and ``np.busday_count`` about 1.5x slower. A weekday is only marked as weekend when it is a non-business day on every
date of the range: calendars with working weekend days (China IB, Russia MOEX) or whose weekend changed (Saudi Arabia)
keep those days in the holiday list.
"""

