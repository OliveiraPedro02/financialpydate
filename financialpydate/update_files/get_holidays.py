def quantlib_non_business_days() -> dict[str, npt.NDArray[np.datetime64]]:
    """
    Every non-business day (weekends included) of each calendar in [FIRST_DATE, END_DATE), from QuantLib.

    QuantLib is queried one year at a time, because some calendars cannot answer for every year: Israel's rules look
    at dates before 1901, and Russia MOEX is only defined for some years. Such years keep the calendar's weekends only
    and are printed, instead of silently leaving the whole calendar empty.
    """
    import QuantLib as ql

    first_year = FIRST_DATE.astype(object).year
    last_date = (END_DATE - 1).astype(object)
    last_ql_date = ql.Date(last_date.day, last_date.month, last_date.year)
    result = {}
    for key, (class_name, market) in CALENDARS.items():
        ql_class = getattr(ql, class_name)
        calendar = ql_class(getattr(ql_class, market)) if market else ql_class()
        dates: list[str] = []
        weekends_only: list[int] = []
        for year in range(first_year, last_date.year + 1):
            first, last = ql.Date(1, 1, year), min(ql.Date(31, 12, year), last_ql_date)
            try:
                dates += [d.ISO() for d in calendar.holidayList(first, last, True)]
            except RuntimeError:
                weekends_only.append(year)
                day = first
                while day <= last:
                    if calendar.isWeekend(day.weekday()):
                        dates.append(day.ISO())
                    day += 1
        if weekends_only:
            print(f'{key}: QuantLib has no holidays for {_year_ranges(weekends_only)}; those years keep weekends only')
        result[key] = np.array(dates, dtype='datetime64[D]')
    return result


def _year_ranges(years: list[int]) -> str:
    """[1901, 1902, 1903, 2026] -> '1901-1903, 2026'."""
    ranges: list[list[int]] = []
    for year in years:
        if ranges and year == ranges[-1][-1] + 1:
            ranges[-1].append(year)
        else:
            ranges.append([year])
    return ', '.join(f'{r[0]}-{r[-1]}' if len(r) > 1 else str(r[0]) for r in ranges)


def split_weekends(non_business_days: npt.NDArray[np.datetime64]) -> tuple[str, npt.NDArray[np.datetime64]]:
    """
    Split a calendar's non-business days into a numpy weekmask and the remaining holidays.

    A weekday is weekend (``'0'`` in the mask) only if it is a non-business day on every date of the range, so the
    pair reproduces exactly the same business days in [FIRST_DATE, END_DATE).
    """
    days = np.arange(FIRST_DATE, END_DATE)
    off = np.isin(days, non_business_days)
    weekday = (days.astype(np.int64) + 3) % 7  # 1970-01-01 was a Thursday; 0 is Monday, as in numpy's weekmask
    always_off = np.array([off[weekday == k].all() for k in range(7)])
    weekmask = ''.join('0' if is_weekend else '1' for is_weekend in always_off)
    return weekmask, days[off & ~always_off[weekday]]


def get_file_name(key: str) -> str:
    base_name, *name_type = key.replace("']", '').split("['")
    if len(name_type) > 0:
        return re.sub(r'(?<!^)(?=[A-Z])', '_', base_name).lower() + '_' + name_type[0].lower()

    return re.sub(r'(?<!^)(?=[A-Z])', '_', base_name).lower()


def get_class_name(key: str) -> str:
    """Attribute name in ``financialpydate.calendars``: ``"Brazil['Exchange']"`` -> ``BrazilExchange``."""
    base_name, *name_type = key.replace("']", '').split("['")
    return base_name + ''.join(name_type)


def write_calendars(non_business_days: dict[str, npt.NDArray[np.datetime64]], directory: Path = CALENDARS_DIR) -> None:
    """Write ``holidays.npz`` and the modules that load it lazily (see the module docstring), then format with ruff."""
    names = list(non_business_days)
    members = [get_file_name(name) for name in names]
    arrays = {'names': np.array(names), 'members': np.array(members)}
    for name, member in zip(names, members, strict=True):
        weekmask, holidays = split_weekends(non_business_days[name])
        arrays[f'{member}_weekmask'] = np.array([flag == '1' for flag in weekmask])
        arrays[f'{member}_holidays'] = holidays.astype(np.int64).astype(np.int32)
    np.savez_compressed(directory / DATA_FILE_NAME, **arrays)

    # One module per calendar and all_calendar.py were written by earlier versions of this script: remove them.
    for stale in [*members, 'all_calendar']:
        (directory / f'{stale}.py').unlink(missing_ok=True)

    class_names = {get_class_name(name): name for name in names}
    entries = ''.join(f'    {class_name!r}: {name!r},\n' for class_name, name in class_names.items())
    exported = ''.join(f'    {class_name!r},\n' for class_name in class_names)
    declarations = ''.join(f'    {class_name}: FinancialCalendar\n' for class_name in class_names)
    (directory / '__init__.py').write_text(
        f"""{GENERATED}from typing import TYPE_CHECKING

from financialpydate import FinancialCalendar
from financialpydate.calendar_store import all_calendars as all_calendars

# Attribute name -> calendar name. Each calendar is built on first access: ``from financialpydate.calendars import Brazil``
# returns the same object as ``all_calendars['Brazil']``.
_NAMES = {{
{entries}}}

__all__ = [
    'all_calendars',
{exported}]

if TYPE_CHECKING:  # lets IDEs and type checkers see the calendars that __getattr__ serves
{declarations}

def __getattr__(name: str) -> FinancialCalendar:
    if name in _NAMES:
        return all_calendars[_NAMES[name]]
    raise AttributeError(f'module {{__name__!r}} has no attribute {{name!r}}')


def __dir__() -> list[str]:
    return sorted([*globals(), *_NAMES])
"""
    )
    subprocess.run(['ruff', 'format', '--quiet', str(directory / '__init__.py')], check=True)


